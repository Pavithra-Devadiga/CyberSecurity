package com.security.scanner.service;

import com.lowagie.text.*;
import com.lowagie.text.pdf.*;
import com.security.scanner.dto.request.ReportGenerateRequest;
import com.security.scanner.dto.response.ReportResponseDto;
import com.security.scanner.entity.Scan;
import com.security.scanner.entity.Vulnerability;
import com.security.scanner.entity.enums.Severity;
import com.security.scanner.exception.ResourceNotFoundException;
import com.security.scanner.repository.ScanRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;

@Service
public class ReportService {

    private final ScanRepository scanRepository;

    public ReportService(ScanRepository scanRepository) {
        this.scanRepository = scanRepository;
    }

    @Transactional(readOnly = true)
    public ReportResponseDto generateReportSummary(ReportGenerateRequest request) {
        Scan scan = scanRepository.findById(request.getScanId())
                .orElseThrow(() -> new ResourceNotFoundException("Scan not found: " + request.getScanId()));

        ReportResponseDto dto = new ReportResponseDto();
        dto.setScanId(scan.getId());
        dto.setTargetUrl(scan.getTargetUrl());
        dto.setFormat(request.getFormat());
        dto.setSecurityScore(scan.getSecurityScore());
        dto.setLetterGrade(scan.getLetterGrade());
        dto.setTotalVulnerabilities(scan.getVulnerabilities() != null ? scan.getVulnerabilities().size() : 0);
        dto.setDownloadUrl("/api/reports/download/" + scan.getId() + "?format=" + request.getFormat());
        dto.setGeneratedAt(LocalDateTime.now());
        return dto;
    }

    @Transactional(readOnly = true)
    public byte[] generatePdfReport(Long scanId) {
        Scan scan = scanRepository.findById(scanId)
                .orElseThrow(() -> new ResourceNotFoundException("Scan not found: " + scanId));

        ByteArrayOutputStream out = new ByteArrayOutputStream();
        Document document = new Document(PageSize.A4, 36, 36, 54, 54);

        try {
            PdfWriter writer = PdfWriter.getInstance(document, out);
            document.open();

            // Document Header
            Font titleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 22, new Color(15, 23, 42));
            Paragraph title = new Paragraph("Security Vulnerability Assessment Report", titleFont);
            title.setAlignment(Element.ALIGN_CENTER);
            title.setSpacingAfter(10);
            document.add(title);

            Font subFont = FontFactory.getFont(FontFactory.HELVETICA, 11, new Color(100, 116, 139));
            Paragraph sub = new Paragraph("Generated by CyberSecurity Automated Platform | "
                    + LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss")), subFont);
            sub.setAlignment(Element.ALIGN_CENTER);
            sub.setSpacingAfter(20);
            document.add(sub);

            // Target Summary Box
            PdfPTable summaryTable = new PdfPTable(2);
            summaryTable.setWidthPercentage(100);
            summaryTable.setSpacingAfter(20);
            summaryTable.setWidths(new float[]{1.5f, 3.5f});

            addSummaryRow(summaryTable, "Target URL:", scan.getTargetUrl());
            addSummaryRow(summaryTable, "Scan Type:", scan.getScanType().name());
            addSummaryRow(summaryTable, "Scan Status:", scan.getStatus().name());
            addSummaryRow(summaryTable, "Security Score:", (scan.getSecurityScore() != null ? scan.getSecurityScore() : "N/A") + "/100");
            addSummaryRow(summaryTable, "Letter Grade:", scan.getLetterGrade() != null ? scan.getLetterGrade() : "N/A");
            addSummaryRow(summaryTable, "TLS Negotiated:", scan.getTlsVersion() != null ? scan.getTlsVersion() : "N/A");
            addSummaryRow(summaryTable, "Technologies:", scan.getTechnologiesFound() != null ? scan.getTechnologiesFound() : "None identified");
            document.add(summaryTable);

            // Severity Breakdown
            List<Vulnerability> vulns = scan.getVulnerabilities() != null ? scan.getVulnerabilities() : List.of();
            long crit = vulns.stream().filter(v -> v.getSeverity() == Severity.CRITICAL).count();
            long high = vulns.stream().filter(v -> v.getSeverity() == Severity.HIGH).count();
            long med = vulns.stream().filter(v -> v.getSeverity() == Severity.MEDIUM).count();
            long low = vulns.stream().filter(v -> v.getSeverity() == Severity.LOW).count();
            long info = vulns.stream().filter(v -> v.getSeverity() == Severity.INFO).count();

            Font secHeader = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 14, new Color(30, 41, 59));
            Paragraph sec1 = new Paragraph("Findings Summary", secHeader);
            sec1.setSpacingAfter(10);
            document.add(sec1);

            PdfPTable countTable = new PdfPTable(5);
            countTable.setWidthPercentage(100);
            countTable.setSpacingAfter(25);
            addBadgeCell(countTable, "CRITICAL: " + crit, new Color(239, 68, 68));
            addBadgeCell(countTable, "HIGH: " + high, new Color(249, 115, 22));
            addBadgeCell(countTable, "MEDIUM: " + med, new Color(234, 179, 8));
            addBadgeCell(countTable, "LOW: " + low, new Color(59, 130, 246));
            addBadgeCell(countTable, "INFO: " + info, new Color(107, 114, 128));
            document.add(countTable);

            // Detailed Findings
            Paragraph sec2 = new Paragraph("Detailed Vulnerability Findings (" + vulns.size() + ")", secHeader);
            sec2.setSpacingAfter(15);
            document.add(sec2);

            if (vulns.isEmpty()) {
                Paragraph clean = new Paragraph("No security vulnerabilities or exposures were detected during this scan.", subFont);
                clean.setSpacingAfter(20);
                document.add(clean);
            } else {
                int index = 1;
                for (Vulnerability v : vulns) {
                    PdfPTable vTable = new PdfPTable(1);
                    vTable.setWidthPercentage(100);
                    vTable.setSpacingAfter(12);

                    PdfPCell cell = new PdfPCell();
                    cell.setPadding(10);
                    cell.setBackgroundColor(new Color(248, 250, 252));
                    cell.setBorderColor(getSeverityColor(v.getSeverity()));
                    cell.setBorderWidth(1.5f);

                    Font hFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 12, new Color(15, 23, 42));
                    Paragraph vTitle = new Paragraph(index++ + ". " + v.getTitle() + " [" + v.getSeverity() + "]", hFont);
                    cell.addElement(vTitle);

                    Font bodyFont = FontFactory.getFont(FontFactory.HELVETICA, 10, new Color(51, 65, 85));
                    if (v.getCwe() != null) cell.addElement(new Paragraph("CWE: " + v.getCwe() + " | Category: " + v.getCategory(), subFont));
                    if (v.getDescription() != null) cell.addElement(new Paragraph("\nDescription: " + v.getDescription(), bodyFont));
                    if (v.getEvidence() != null) cell.addElement(new Paragraph("\nEvidence:\n" + v.getEvidence(), bodyFont));
                    if (v.getRemediation() != null) {
                        Font remFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, new Color(22, 101, 52));
                        cell.addElement(new Paragraph("\nRemediation Guidance:\n" + v.getRemediation(), remFont));
                    }

                    vTable.addCell(cell);
                    document.add(vTable);
                }
            }

            document.close();
            return out.toByteArray();

        } catch (Exception e) {
            throw new RuntimeException("Failed to generate PDF report: " + e.getMessage(), e);
        }
    }

    private void addSummaryRow(PdfPTable table, String label, String value) {
        Font lFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, new Color(71, 85, 105));
        Font vFont = FontFactory.getFont(FontFactory.HELVETICA, 10, new Color(15, 23, 42));

        PdfPCell lCell = new PdfPCell(new Phrase(label, lFont));
        lCell.setBorder(Rectangle.NO_BORDER);
        lCell.setPadding(4);
        table.addCell(lCell);

        PdfPCell vCell = new PdfPCell(new Phrase(value, vFont));
        vCell.setBorder(Rectangle.NO_BORDER);
        vCell.setPadding(4);
        table.addCell(vCell);
    }

    private void addBadgeCell(PdfPTable table, String text, Color bg) {
        Font bFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, Color.WHITE);
        PdfPCell cell = new PdfPCell(new Phrase(text, bFont));
        cell.setBackgroundColor(bg);
        cell.setHorizontalAlignment(Element.ALIGN_CENTER);
        cell.setPadding(6);
        cell.setBorder(Rectangle.NO_BORDER);
        table.addCell(cell);
    }

    private Color getSeverityColor(Severity s) {
        if (s == null) return Color.GRAY;
        return switch (s) {
            case CRITICAL -> new Color(239, 68, 68);
            case HIGH -> new Color(249, 115, 22);
            case MEDIUM -> new Color(234, 179, 8);
            case LOW -> new Color(59, 130, 246);
            case INFO -> new Color(107, 114, 128);
        };
    }
}
